import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const editor = await readFile('apps/renderer/src/features/settings/ConfiguredModelsEditor.vue', 'utf8');
const dialog = await readFile('apps/renderer/src/features/settings/ModelTestDialog.vue', 'utf8');
assert.match(editor, /v-for="model in visibleModels"/);
assert.match(editor, /@click="testingModel = model">测试/);
assert.match(editor, /<ModelTestDialog/);
assert.match(dialog, /testConfiguredModelCapability/);
assert.match(dialog, /模型测试生成结果/);
assert.match(dialog, /<audio/);
assert.match(dialog, /选择测试图片/);
assert.match(dialog, /选择测试音频/);
assert.match(dialog, /1024x1024/);
for (const capability of ['chat', 'vision', 'image', 'embedding', 'asr', 'tts', 'quantum-code']) assert.match(dialog, new RegExp(capability));
assert.match(dialog, /role="dialog"/);
assert.match(dialog, /aria-modal="true"/);
assert.match(dialog, /max-h-\[calc\(100dvh-2rem\)\]/);
assert.match(dialog, /min-h-0 flex-1 space-y-4 overflow-y-auto/);
assert.match(dialog, /<header class="flex shrink-0/);
assert.match(dialog, /<footer class="flex shrink-0/);
assert.match(dialog, /role="progressbar"/);
assert.match(dialog, /aria-valuenow/);
assert.match(dialog, /progressStage/);
assert.match(dialog, /Math\.min\(92/);
assert.doesNotMatch(dialog, /@click\.self="emit\('close'\)"/);
assert.match(dialog, /aria-label="关闭" :disabled="running"/);
assert.match(dialog, /请等待测试完成/);
assert.match(dialog, /:aria-busy="running"/);
console.log('MODEL-TEST-T1 PASS: every configured model exposes the capability-aware test dialog.');
