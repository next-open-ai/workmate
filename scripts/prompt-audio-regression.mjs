import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createServer } from '../apps/renderer/node_modules/vite/dist/node/index.js';

// No provider traffic and no user settings reads/writes.
const server = await createServer({ root: process.cwd(), configFile: false, optimizeDeps: { noDiscovery: true, include: [] }, server: { host: '127.0.0.1', middlewareMode: true }, appType: 'custom' });
try {
  const { providerSuggestedByCapability, applyRecommendedProviderSetup, effectiveProviderBaseUrl, qwenNextNeedsWorkspace, bindSpecialistModel } = await server.ssrLoadModule('/apps/renderer/src/app/model-config.ts');
  assert.ok(providerSuggestedByCapability.qwen.tts.includes('qwen-audio-3.1-tts-next'));
  const provider = { id: 'ali', type: 'qwen', name: '阿里', baseUrl: 'https://dashscope.aliyuncs.com/compatible-mode/v1', workspaceId: 'example', service: 'unified', apiKey: 'fake-key', disableThinking: false };
  assert.equal(effectiveProviderBaseUrl(provider, 'tts'), 'https://example.cn-beijing.maas.aliyuncs.com/api/v1');
  const empty = { version: 3, providerInstances: [], models: [], activeChatModelId: null, activeEmbeddingModelId: null, employeeDefaultModelIds: {}, capabilityBindings: [], agentCapabilityAssignments: [] };
  const setup = applyRecommendedProviderSetup(empty, provider, ['general']);
  assert.equal(setup.settings.models.find((model) => model.capability === 'tts').modelId, 'qwen-audio-3.1-tts-flash', 'adding AudioGen must not silently replace the default TTS');
  const nextId = 'qwen-audio-3.1-tts-next';
  const candidate = { id: 'next-model', providerInstanceId: provider.id, capability: 'tts', modelId: nextId };
  const firstBinding = bindSpecialistModel([], candidate);
  assert.equal(firstBinding[0].modelId, candidate.id);
  assert.equal(firstBinding[0].enabled, true);
  const disabled = [{ capability: 'tts', modelId: 'old-tts', enabled: false, updatedAt: 'old' }];
  assert.deepEqual(bindSpecialistModel(disabled, candidate), disabled, 'registration cannot override disabled bindings');
  const enabled = [{ ...disabled[0], enabled: true }];
  assert.deepEqual(bindSpecialistModel(enabled, candidate), enabled, 'registration cannot replace an existing default');
  const existing = [...disabled, { capability: 'image', modelId: 'image-model', enabled: true, updatedAt: 'old' }];
  const activated = bindSpecialistModel(existing, candidate, true);
  assert.equal(activated.find((item) => item.capability === 'tts').modelId, candidate.id);
  assert.equal(activated.find((item) => item.capability === 'tts').enabled, true);
  assert.deepEqual(activated.find((item) => item.capability === 'image'), existing[1]);
  assert.deepEqual(existing[0], disabled[0], 'activation cannot mutate previous settings');
  assert.deepEqual(bindSpecialistModel([], { ...candidate, capability: 'chat' }, true), []);
  const nextModels = (settings, providerId = provider.id) => settings.models.filter((model) => model.providerInstanceId === providerId && model.capability === 'tts' && model.modelId === nextId);
  assert.equal(nextModels(setup.settings).length, 1);
  assert.equal(nextModels(setup.settings)[0].voice, undefined);
  const ttsBinding = setup.settings.capabilityBindings.find((binding) => binding.capability === 'tts');
  assert.equal(setup.settings.models.find((model) => model.id === ttsBinding.modelId).modelId, 'qwen-audio-3.1-tts-flash');
  const repeated = applyRecommendedProviderSetup(setup.settings, provider, ['general']);
  assert.equal(repeated.addedModels, 0); assert.deepEqual(repeated.settings, setup.settings);
  const legacy = structuredClone(setup.settings);
  legacy.models = legacy.models.filter((model) => model.modelId !== nextId);
  const customTts = legacy.models.find((model) => model.capability === 'tts');
  customTts.voice = 'custom-voice';
  legacy.agentCapabilityAssignments.find((assignment) => assignment.capability === 'tts').mode = 'disabled';
  const filled = applyRecommendedProviderSetup(legacy, provider, ['general']);
  assert.equal(filled.addedModels, 1);
  assert.deepEqual(filled.settings.capabilityBindings, legacy.capabilityBindings);
  assert.deepEqual(filled.settings.agentCapabilityAssignments, legacy.agentCapabilityAssignments);
  assert.equal(filled.settings.models.find((model) => model.id === customTts.id).voice, 'custom-voice');
  const handConfigured = structuredClone(setup.settings);
  const manualNext = nextModels(handConfigured)[0]; manualNext.label = '我的歌曲模型';
  handConfigured.capabilityBindings.find((binding) => binding.capability === 'tts').modelId = manualNext.id;
  const kept = applyRecommendedProviderSetup(handConfigured, provider);
  assert.equal(kept.addedModels, 0); assert.deepEqual(kept.settings, handConfigured);
  for (const service of ['language', 'realtime']) assert.equal(nextModels(applyRecommendedProviderSetup(empty, { ...provider, service }).settings).length, 0);
  assert.equal(nextModels(applyRecommendedProviderSetup(empty, { ...provider, service: 'speech' }).settings).length, 1);
  assert.equal(nextModels(applyRecommendedProviderSetup(empty, { ...provider, workspaceId: '' }).settings).length, 1);
  const secondProvider = { ...provider, id: 'ali-second' };
  const second = applyRecommendedProviderSetup(setup.settings, secondProvider);
  assert.equal(nextModels(second.settings, 'ali-second').length, 1);
  assert.deepEqual(second.settings.capabilityBindings, setup.settings.capabilityBindings);
  const editor = await readFile('apps/renderer/src/features/settings/ConfiguredModelsEditor.vue', 'utf8');
  assert.match(editor, /isQwenPromptAudioModel/);
  assert.match(editor, /提示词音频生成：无需音色 ID/);
  assert.match(editor, /bindSpecialistModel\(props.capabilityBindings, entry, makeDefault\)/);
  assert.match(editor, /emit\('activate-audio', model.id\)/);
  assert.match(editor, /未启用音频创作/);
  const dialog = await readFile('apps/renderer/src/features/settings/ModelTestDialog.vue', 'utf8');
  assert.match(dialog, /voice: promptAudio \? undefined : props.model.voice/);
  assert.match(dialog, /原创歌词/);
  const missingWorkspace = { ...provider, workspaceId: '' };
  assert.equal(qwenNextNeedsWorkspace(missingWorkspace, setup.settings.models), true);
  assert.equal(qwenNextNeedsWorkspace(provider, setup.settings.models), false);
  assert.equal(qwenNextNeedsWorkspace({ ...missingWorkspace, type: 'openai' }, setup.settings.models), false);
  assert.equal(qwenNextNeedsWorkspace(missingWorkspace, []), false);
  assert.equal(qwenNextNeedsWorkspace({ ...missingWorkspace, endpoints: { tts: 'https://example.cn-beijing.maas.aliyuncs.com/api/v1' } }, setup.settings.models), false);
  const providerEditor = await readFile('apps/renderer/src/features/settings/ProviderInstancesEditor.vue', 'utf8');
  assert.match(providerEditor, /v-if="nextNeedsWorkspace\(instance\)"/);
  assert.match(providerEditor, /@click="editingId = instance.id"/);
  const settingsPage = await readFile('apps/renderer/src/features/settings/SettingsPage.vue', 'utf8');
  assert.match(settingsPage, /qwenNextNeedsWorkspace\(instance, result.settings.models\)/);
  assert.match(settingsPage, /@activate-audio="activateAudioModel"/);
  assert.match(settingsPage, /bindSpecialistModel\(settings.value.capabilityBindings, model, true\)/);
  assert.match(settingsPage, /async function activateAudioModel[\s\S]*?await saveModelConfig\(\)/);
  const i18n = await readFile('apps/renderer/src/app/i18n.ts', 'utf8');
  assert.match(i18n, /使用 Next 时必填/);
  assert.match(i18n, /默认业务空间也需要/);
  const pi = await readFile('packages/agent-core/src/pi-runtime.ts', 'utf8');
  assert.match(pi, /toolName === 'model_generate_audio'/);
  assert.doesNotMatch(pi, /A previous turn's network error|Readiness: configured/);
  console.log('AMC-AUDIOGEN AT4/AT5/AT6/AT9/AT11 PASS: auto-configuration, explicit binding, preservation and setup guidance.');
} finally { await server.close(); }
