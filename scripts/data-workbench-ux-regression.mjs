import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(new URL('../apps/renderer/package.json', import.meta.url));
const ts = require('typescript');
const file = new URL('../apps/renderer/src/features/data/workbench-presentation.ts', import.meta.url);
const { outputText } = ts.transpileModule(readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.ES2022 } });
const { appPresentation, matchesSource, sourceNextStep } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
assert.deepEqual(appPresentation({ delivery: { status: 'awaiting-binding' } }), { pending: true, label: '待交付', primary: '继续创建', canShare: false });
assert.equal(appPresentation({ customSite: { bound: true } }).label, '定制应用 · 可用');
assert.equal(appPresentation({}).primary, '打开应用');
assert.equal(appPresentation({}).canShare, true);
const source = { name: '订单数据', fileType: 'CSV', summary: '交易明细', annotations: { description: '已支付订单', connectionDescription: '每日更新' } };
for (const query of ['', '  ', 'csv 订单', '支付', '每日']) assert.equal(matchesSource(source, query), true);
assert.equal(matchesSource(source, '退款'), false);
assert.equal(matchesSource(source, '订单 PDF'), false);
assert.equal(sourceNextStep(false, 0, 2).action, 'description');
assert.equal(sourceNextStep(true, 1, 2).action, 'fields');
assert.equal(sourceNextStep(true, 2, 2).action, 'create');
assert.equal(sourceNextStep(true, 0, 0).action, 'create');
console.log('DAC-R6 PASS: search, delivery actions, sharing visibility, legacy fallback and next-step guidance.');
